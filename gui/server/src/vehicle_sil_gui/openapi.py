def default_protocol_dir() -> Path:
    """Returns `<repo>/gui/protocol` for a repository checkout."""
    return Path(__file__).resolve().parents[3] / "protocol"


def _canonicalize_schema(node: Any) -> Any:
    """Deterministically orders schema combinators (`anyOf`/`oneOf`) and mappings across Python 3.11-3.14."""
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for k, v in node.items():
            if k == "$defs" and isinstance(v, dict):
                out[k] = {dk: _canonicalize_schema(v[dk]) for dk in sorted(v)}
            elif k in ("anyOf", "oneOf") and isinstance(v, list):
                items = [_canonicalize_schema(item) for item in v]
                out[k] = sorted(items, key=lambda item: json.dumps(item, sort_keys=True, ensure_ascii=False))
            elif k == "discriminator" and isinstance(v, dict):
                disc = dict(v)
                if isinstance(disc.get("mapping"), dict):
                    disc["mapping"] = {mk: disc["mapping"][mk] for mk in sorted(disc["mapping"])}
                out[k] = disc
            else:
                out[k] = _canonicalize_schema(v)
        return out
    if isinstance(node, list):
        return [_canonicalize_schema(item) for item in node]
    return node


def _collect_openapi_schemas(routes: tuple[RouteSpec, ...]) -> tuple[dict[Any, dict[str, Any]], dict[str, Any]]:
    """Generates unified `#/components/schemas/*` definitions for all routes and shared contracts."""
    named_unions: list[tuple[str, Any, str]] = [
        (
            "TimeCommand",
            TimeCommand,
            "Normalized time command payload without `run_id` or `instance` targeting fields.",
        ),
        (
            "TimeCommandRequest",
            TimeCommandRequest,
            "Request body for `POST /api/time`. Protocol v4 preserves omitting both `run_id` and `instance` "
            "unchanged for compatibility (targeting whichever run is current), but new clients, AI agents, "
            "and CI automation should always send both `instance` and `run_id`. Supplying only one fails with "
            "`400 invalid-field`.",
        ),
        (
            "CheckRequest",
            CheckRequest,
            "Request body for `POST /api/check`: either unsaved configuration text (`CheckTextRequest`) or "
            "a saved configuration file with optional run-request overrides (`RunRequest`).",
        ),
    ]
    union_names: dict[Any, str] = {typ: name for name, typ, _ in named_unions}
    named_unions_map: dict[str, Any] = {name: typ for name, typ, _ in named_unions}

    inputs: list[tuple[Any, str, Any]] = []
    seen_keys: set[Any] = set()

    def register(key: Any, target: Any) -> None:
        if key in seen_keys:
            return
        seen_keys.add(key)
        core = (
            target.__pydantic_core_schema__
            if isinstance(target, type) and issubclass(target, BaseModel)
            else TypeAdapter(target).core_schema
        )
        inputs.append((key, "validation", core))

    # Shared & named component schemas first
    register(ErrorBody, ErrorBody)
    register(ErrorResponse, ErrorResponse)
    register(RunTarget, RunTarget)
    for name, typ, _ in named_unions:
        register(name, typ)

    for spec in routes:
        if spec.request_model is not None and spec.request_model not in union_names:
            register(spec.request_model, spec.request_model)
        if spec.response_model is not None and spec.response_model not in union_names:
            register(spec.response_model, spec.response_model)

    generator = ContractJsonSchemaGenerator(ref_template=REF_TEMPLATE)
    key_map, raw_defs = generator.generate_definitions(inputs)
    defs: dict[str, Any] = dict(raw_defs)

    refs: dict[Any, dict[str, Any]] = {}
    for orig_key, mode, _ in inputs:
        top_schema = key_map[(orig_key, mode)]
        if isinstance(orig_key, str):
            desc = next(d for n, _, d in named_unions if n == orig_key)
            component = dict(top_schema)
            component["description"] = desc
            defs[orig_key] = component
            refs[named_unions_map[orig_key]] = {"$ref": f"#/components/schemas/{orig_key}"}
        else:
            refs[orig_key] = top_schema

    # Point TimeCommandAck.command to named TimeCommand component schema for clean reuse
    if "TimeCommandAck" in defs and "TimeCommand" in defs:
        ack = dict(defs["TimeCommandAck"])
        props = dict(ack.get("properties", {}))
        props["command"] = {"$ref": "#/components/schemas/TimeCommand"}
        ack["properties"] = props
        defs["TimeCommandAck"] = ack

    sorted_defs = {name: _canonicalize_schema(defs[name]) for name in sorted(defs)}
    return refs, sorted_defs


def build_openapi_document() -> dict[str, Any]:
    """Builds the complete OpenAPI 3.1.0 document for all 17 `/api/*` endpoints."""
    routes = route_specs()
    refs, schemas = _collect_openapi_schemas(routes)

    paths: dict[str, dict[str, Any]] = {}
    for spec in routes:
        op: dict[str, Any] = {
            "operationId": spec.operation_id,
            "summary": spec.summary,
        }
        if spec.tags:
            op["tags"] = list(spec.tags)
        if spec.description:
            op["description"] = spec.description

        params: list[dict[str, Any]] = []
        for pname in spec.path_params:
            params.append({
                "name": pname,
                "in": "path",
                "required": True,
                "description": PATH_PARAM_DESCRIPTIONS.get(pname, f"Path parameter `{pname}`."),
                "schema": {"type": "string", "minLength": 1},
            })
        for qname in spec.query_params:
            params.append({
                "name": qname,
                "in": "query",
                "required": True,
                "description": QUERY_PARAM_DESCRIPTIONS.get(qname, f"Query parameter `{qname}`."),
                "schema": {"type": "string", "minLength": 1},
            })
        if params:
            op["parameters"] = params

        if spec.request_model is not None:
            media_obj: dict[str, Any] = {"schema": refs[spec.request_model]}
            if spec.operation_id in REQUEST_EXAMPLES:
                media_obj["examples"] = REQUEST_EXAMPLES[spec.operation_id]
            op["requestBody"] = {
                "required": spec.request_body_required,
                "content": {"application/json": media_obj},
            }

        responses: dict[str, Any] = {}
        ok_schema = refs[spec.response_model] if spec.response_model is not None else {"type": "object"}
        responses["200"] = {
            "description": SUCCESS_DESCRIPTIONS.get(spec.operation_id, "Success."),
            "content": {spec.response_media_type: {"schema": ok_schema}},
        }
        for status in spec.error_statuses:
            err_desc = ERROR_DESCRIPTIONS[status]
            if status == 413 and spec.method == "POST":
                if spec.max_body == MAX_TEXT_BODY:
                    err_desc = (
                        f"Request body exceeds {spec.max_body} bytes (`too-large`) or UTF-8 `text` "
                        f"exceeds {MAX_TEXT} bytes (`text-too-large`)."
                    )
                else:
                    err_desc = f"Request body exceeds {spec.max_body} bytes (`too-large`)."
            responses[str(status)] = {
                "description": err_desc,
                "content": {"application/json": {"schema": {"$ref": "#/components/schemas/ErrorResponse"}}},
            }
        op["responses"] = responses

        paths.setdefault(spec.path, {})[spec.method.lower()] = op

    return {
        "openapi": "3.1.0",
        "info": {
            "title": "vehicle-sil GUI Server API",
            "version": str(PROTOCOL),
            "summary": f"Machine-readable contract for all {len(routes)} HTTP endpoints of vehicle_sil_gui protocol {PROTOCOL}",
            "description": API_DESCRIPTION,
        },
        "servers": [
            {
                "url": "http://127.0.0.1:8765",
                "description": "Local GUI server (loopback only; actual port is configured or ephemeral)",
            }
        ],
        "security": [{"bearerAuth": []}],
        "tags": TAGS,
        "paths": paths,
        "components": {
            "securitySchemes": {
                "bearerAuth": {
                    "type": "http",
                    "scheme": "bearer",
                    "description": (
                        "Per-run bearer token printed by `vehicle-sil-gui` (`Authorization: Bearer <token>`). "
                        "Authentication is disabled when the server is started with `--no-auth`."
                    ),
                }
            },
            "schemas": schemas,
        },
    }


def build_ws_server_schema() -> dict[str, Any]:
    """Draft 2020-12 JSON Schema covering all 13 server -> client WebSocket frames."""
    raw = WS_SERVER_MESSAGE_ADAPTER.json_schema(schema_generator=ContractJsonSchemaGenerator)
    return _canonicalize_schema({
        "$schema": DRAFT_2020_12,
        "title": "vehicle-sil GUI WebSocket server-to-client message (Protocol v4)",
        "description": (
            "Draft 2020-12 JSON Schema for all 13 server-to-client WebSocket frames on `/ws` (Protocol v4). "
            "Behavioral invariants documented in `gui/protocol/README.md`: `hello.stream_seq` is the stream head; "
            "replayed log events carry `stream_seq <= hello.stream_seq`; live frames after `synced` have strictly "
            "increasing `stream_seq`; `values`, `dropped`, and `resync` never carry `stream_seq`; `hello.session` "
            "includes `variables` while `session` frames omit `variables`."
        ),
        **raw,
    })


