"""Offline deterministic OpenAPI 3.1.0 and Draft 2020-12 JSON Schema exporter (`vehicle_sil_gui: 4`).

Generates all machine-readable HTTP, WebSocket, and CLI contracts directly from `server.route_specs()`
and `contracts.py` without starting a server, opening sockets, or probing the launcher:

  - `gui/protocol/openapi.yaml`                        (all 17 `/api/*` HTTP endpoints)
  - `gui/protocol/schemas/ws-server.schema.json`       (all 13 server -> client WebSocket frames)
  - `gui/protocol/schemas/ws-client.schema.json`       (all 3 client -> server WebSocket frames)
  - `gui/protocol/schemas/ws-command-event.schema.json` (asynchronous WebSocket `command` event)
  - `gui/protocol/schemas/cli-json.schema.json`        (`vehicle-sil-gui --json` readiness message)

Usage:
    python -m vehicle_sil_gui.openapi --write [--out DIR]
    python -m vehicle_sil_gui.openapi --check [--out DIR]
    python -m vehicle_sil_gui.openapi --stdout [TARGET]
"""

