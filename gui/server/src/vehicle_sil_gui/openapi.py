def render_yaml(doc: dict[str, Any]) -> str:
    body = yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)
    return (YAML_HEADER + body).replace("\r\n", "\n")


def render_json(doc: dict[str, Any]) -> str:
    return (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").replace("\r\n", "\n")


def render_all() -> dict[str, str]:
    """Returns `{relative_posix_path: deterministic_utf8_text}` for all generated protocol artifacts."""
    return {
        "openapi.yaml": render_yaml(build_openapi_document()),
        "schemas/ws-server.schema.json": render_json(build_ws_server_schema()),
        "schemas/ws-client.schema.json": render_json(build_ws_client_schema()),
        "schemas/ws-command-event.schema.json": render_json(build_ws_command_event_schema()),
        "schemas/cli-json.schema.json": render_json(build_cli_json_schema()),
    }


def write_all(out_dir: Path | None = None) -> list[Path]:
    """Writes all generated protocol artifacts deterministically with LF line endings."""
    root = out_dir or default_protocol_dir()
    written: list[Path] = []
    for rel, text in render_all().items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def check_all(out_dir: Path | None = None) -> list[str]:
    """Checks byte-for-byte parity between generated artifacts and files on disk. Returns mismatch messages."""
    root = out_dir or default_protocol_dir()
    problems: list[str] = []
    for rel, expected in render_all().items():
        path = root / rel
        if not path.is_file():
            problems.append(f"{rel}: missing (run `python -m vehicle_sil_gui.openapi --write`)")
            continue
        actual = path.read_bytes().decode("utf-8")
        if actual != expected:
            diff = "".join(
                difflib.unified_diff(
                    actual.splitlines(keepends=True),
                    expected.splitlines(keepends=True),
                    fromfile=f"disk/{rel}",
                    tofile=f"generated/{rel}",
                    n=2,
                )
            )
            preview = "\n".join(diff.splitlines()[:40])
            problems.append(f"{rel}: out of date (run `python -m vehicle_sil_gui.openapi --write`)\n{preview}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m vehicle_sil_gui.openapi",
        description="Generate or check deterministic OpenAPI 3.1.0 and WebSocket/CLI JSON Schemas offline.",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write generated schema files under --out")
    mode.add_argument("--check", action="store_true", help="exit 0 iff files under --out match byte-for-byte")
    mode.add_argument(
        "--stdout",
        nargs="?",
        const="openapi.yaml",
        choices=TARGETS,
        metavar="TARGET",
        help="print one generated schema to stdout (default: openapi.yaml)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="target protocol directory (default: gui/protocol in the repository)",
    )
    args = parser.parse_args(argv)
    if args.stdout is not None:
        sys.stdout.write(render_all()[args.stdout])
        return 0
    if args.write:
        written = write_all(args.out)
        print(f"openapi: wrote {len(written)} files to {args.out or default_protocol_dir()}")
        return 0
    problems = check_all(args.out)
    if problems:
        for problem in problems:
            print(f"openapi: DRIFT {problem}", file=sys.stderr)
        return 1
    print(f"openapi: ok ({len(render_all())} files match byte-for-byte)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
